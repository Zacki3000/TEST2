static int cmd_start_tx_test(int, char **)
{
    if (tx_timer_handle != NULL)
    {
        ESP_LOGW(TAG, "tx timer already created");
        return 1;
    }

    esp_timer_create_args_t create_args = {
        .callback = tx_timer_cb,
        .arg = NULL,
        .name = "tx"
    };
    esp_err_t res = esp_timer_create(&create_args, &tx_timer_handle);
    if (res != ESP_OK)
    {
        ESP_LOGE(TAG, "esp_timer_create failed: %s", esp_err_to_name(res));
        return 1;
    }

    res = esp_timer_start_periodic(tx_timer_handle, 100000);
    if (res != ESP_OK)
    {
        ESP_LOGE(TAG, "esp_timer_start_periodic failed: %s", esp_err_to_name(res));
        return 1;
    }

    return 0;
}

void register_tx_test(void)
{
    const esp_console_cmd_t cmd = {
        .command = "tx_test",
        .help = "start sending 10 packets per second",
        .hint = NULL,
        .func = &cmd_start_tx_test,
        .argtable = NULL
    };
    ESP_ERROR_CHECK(esp_console_cmd_register(&cmd));
}

